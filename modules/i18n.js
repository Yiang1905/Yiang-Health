  let currentLang = 'en';

  function detectLanguage() {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && (SUPPORTED.includes(stored) || T[stored])) return stored;

    const nav = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    if (nav.startsWith('zh')) {
      if (nav.includes('tw') || nav.includes('hk') || nav.includes('hant')) return 'zh-TW';
      return 'zh-CN';
    }
    const short = nav.split('-')[0];
    if (SUPPORTED.includes(nav)) return nav;
    if (SUPPORTED.includes(short)) return short;
    if (T[nav]) return nav;
    if (T[short]) return short;
    return 'en';
  }

  function setLanguage(lang) {
    if (!T[lang] && !SUPPORTED.includes(lang)) lang = 'en';
    currentLang = lang;
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = RTL.includes(lang) ? 'rtl' : 'ltr';
    applyTranslations();
    // Dispatch for other modules
    window.dispatchEvent(new CustomEvent('yiang:langchange', { detail: { lang } }));
  }

  function t(key) {
    const dict = T[currentLang] || T.en;
    return dict[key] || T.en[key] || key;
  }

  function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el.hasAttribute('placeholder')) el.placeholder = val;
      } else {
        el.textContent = val;
      }
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    // Update lang selector if present
    const sel = document.getElementById('lang-select');
    if (sel) sel.value = currentLang;
  }

  function init() {
    currentLang = detectLanguage();
    document.documentElement.lang = currentLang;
    document.documentElement.dir = RTL.includes(currentLang) ? 'rtl' : 'ltr';
    applyTranslations();
  }

  function getCurrentLang() {
    return currentLang;
  }

  function getSupported() {
    return SUPPORTED.slice();
  }

  return {
    init,
    setLanguage,
    t,
    getCurrentLang,
    getSupported,
    applyTranslations,
    T // expose for advanced use
  };
